/**
 * Build the browser half of the plugin.
 *
 * Output: `lib/client.js` — one classic script that calls
 * `window.__ModuleLoader__.load({ id, factory })`, exactly the shape
 * `@deepseek-ai/dsh-client-modules` materializes for `dsh.client` packages.
 *
 * `src/client.js` is already written as the factory body (CommonJS, importing
 * only the platform seed modules the shell provides), so there is no bundler:
 * this step only wraps the file and gates the specifiers it may `require`.
 * Keeping it dependency-free means the repo builds with a bare `node` and no
 * `pnpm install`, which matters on machines where optional platform binaries
 * are not linked (e.g. `@esbuild/win32-x64` under pnpm 9 + ignored build scripts).
 *
 * Usage: node scripts/build.mjs
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = dirname(here);

const manifest = JSON.parse(await readFile(join(root, "package.json"), "utf8"));

/** Must equal package.json "name": the loader keys rows/factories by package name. */
const PLUGIN_ID = manifest.name;

/**
 * Modules the shell provides at runtime (the platform seed table of
 * `@deepseek-ai/dsh-web-frontend`). The factory body may `require` only these.
 */
const PLATFORM_SEEDS = new Set([
  "react",
  "react/jsx-runtime",
  "react-dom",
  "react-dom/client",
  "@deepseek-ai/cordis",
  "zod",
  "@tanstack/react-virtual",
  "@deepseek-ai/dsh-client-store",
  "@deepseek-ai/dsh-client-ui-slots",
  "@deepseek-ai/dsh-client-ui-primitives",
  "@deepseek-ai/dsh-client-ui-dockkit",
]);

// Normalize line endings first: a Windows checkout with core.autocrlf=true
// hands us CRLF, which would otherwise make the generated bundle differ from
// the committed one for purely local reasons (and dirty the working tree).
const body = (await readFile(join(root, "src", "client.js"), "utf8")).replace(/\r\n/g, "\n").trimEnd();

// Purity gate: every require() the body performs must be a platform seed,
// otherwise the shell cannot materialize the module at load time.
const requested = [...body.matchAll(/require\(\s*["']([^"']+)["']\s*\)/g)].map((m) => m[1]);
const unlisted = [...new Set(requested)].filter((spec) => !PLATFORM_SEEDS.has(spec));
if (unlisted.length > 0) {
  throw new Error(
    `bundle purity gate: not a platform seed: ${unlisted.join(", ")} ` +
      `(add it to PLATFORM_SEEDS only if the shell really provides it)`,
  );
}

const banner = `/* ${PLUGIN_ID} v${manifest.version} — generated by scripts/build.mjs, do not edit */`;
const wrapped = `${banner}
window.__ModuleLoader__.load({
\tid: ${JSON.stringify(PLUGIN_ID)},
\tfactory: (require) => {
\t\tvar module = { exports: {} };
\t\tvar exports = module.exports;
\t\tObject.defineProperty(exports, Symbol.toStringTag, { value: "Module" });
${body}
\t\treturn module.exports;
\t}
});
`;

const outFile = join(root, "lib", "client.js");
await mkdir(dirname(outFile), { recursive: true });
await writeFile(outFile, wrapped, "utf8");
const bytes = (await readFile(outFile)).byteLength;
console.log(
  `built lib/client.js (${bytes} bytes), runtime requires: ${[...new Set(requested)].join(", ") || "none"}`,
);
